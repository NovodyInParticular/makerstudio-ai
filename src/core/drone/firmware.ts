export type ImuFacing = "front" | "back" | "left" | "right";
export interface DroneCodeOptions {
  boardId: string;
  motorPins: number[];
  /** Where the arrow printed as X on the IMU board points, and whether the chip faces up. */
  imuX: ImuFacing;
  imuUp: boolean;
  batteryPin: number | null;
  /** Battery divider ratio (2 for two equal resistors). */
  batteryDivider: number;
  /** A VL53L1X distance sensor looking down, on the IMU's I²C bus, for height hold. */
  heightSensor?: boolean;
  wifiName: string;
  wifiPassword: string;
}

/** Body axes: x right, y back, z up (front is -Y). */
const DIR: Record<ImuFacing, [number, number, number]> = { front: [0, -1, 0], back: [0, 1, 0], left: [-1, 0, 0], right: [1, 0, 0] };

/** Rotation from IMU axes to body axes (rows = body x, y, z; columns = IMU x, y, z). */
export function imuToBody(imuX: ImuFacing, up: boolean): number[] {
  const x = DIR[imuX];
  const z: [number, number, number] = up ? [0, 0, 1] : [0, 0, -1];
  const y: [number, number, number] = [z[1] * x[2] - z[2] * x[1], z[2] * x[0] - z[0] * x[2], z[0] * x[1] - z[1] * x[0]]; // y = z × x
  return [x[0], y[0], z[0], x[1], y[1], z[1], x[2], y[2], z[2]];
}

const num = (n: number) => { const s = String(Math.abs(n) < 1e-15 ? 0 : n); return /[.eE]/.test(s) ? s : `${s}.0`; };

/** The flight controller settings of a design, as the C++ FcConfig (also used by the parity test). */
export function flightConfigHeader(drone: Drone, objects: CadObject[], report: DroneReport = analyseDrone(drone, objects)): string {
  const p = simParams(drone, objects, report);
  const mix = mixerMatrix(p.motors.map((m) => ({ x: m.r[0], y: m.r[1], spin: m.spin })));
  if (!mix) throw new Error("With motors in these places the drone cannot be steered (see Will it fly?).");
  const pid = (q: Drone["pid"]["rollPitch"]) => `{${num(q.angleP)}, ${num(q.rateP)}, ${num(q.rateI)}, ${num(q.rateD)}}`;
  return [
    "// Generated by MakerStudio Drone Studio from your design. Do not edit: export again instead.",
    "#pragma once",
    '#include "flight_core.h"',
    "",
    `static const FcConfig FC_CONFIG = {`,
    `  ${mix.length},`,
    `  {${mix.map((row) => `{${row.map(num).join(", ")}}`).join(", ")}},`,
    `  {${p.inertia.map(num).join(", ")}},`,
    `  ${num(p.maxThrust)},`,
    `  ${pid(drone.pid.rollPitch)},`,
    `  ${pid(drone.pid.yaw)},`,
    `  ${num(LIMITS.maxTilt)}, ${num(LIMITS.maxYawRate)},`,
    `};`,
    `static const double HOVER_SHARE = ${num(Math.min(0.95, report.hoverThrottle))}; // estimated hover throttle`,
    "",
  ].join("\n");
}

function droneConfigHeader(drone: Drone, opts: DroneCodeOptions, board: DroneBoard, report: DroneReport): string {
  const R = imuToBody(opts.imuX, opts.imuUp);
  const esc = (s: string) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return [
    "// Generated by MakerStudio Drone Studio. Pins and options for your drone.",
    "#pragma once",
    `#define BOARD_NAME "${board.name}"`,
    `#define MOTOR_COUNT ${drone.motors.length}`,
    `static const int MOTOR_PINS[MOTOR_COUNT] = {${opts.motorPins.join(", ")}};`,
    `#define I2C_SDA ${board.sda}`,
    `#define I2C_SCL ${board.scl}`,
    `// IMU X arrow points ${opts.imuX}, chip ${opts.imuUp ? "up" : "down"}: IMU axes -> body axes (x right, y back, z up)`,
    `static const double IMU_TO_BODY[9] = {${R.map(num).join(", ")}};`,
    `#define HEIGHT_SENSOR ${opts.heightSensor ? 1 : 0}   // VL53L1X looking down: height hold`,
    `#define DRONE_MASS_KG ${num(Math.round(report.total.mass) / 1000)}   // from Will it fly? (estimate)`,
    `#define BATTERY_PIN ${opts.batteryPin ?? -1}`,
    `#define BATTERY_DIVIDER ${num(opts.batteryDivider)}`,
    `#define BATTERY_CELLS ${drone.battery.cells}`,
    `#define WIFI_NAME "${esc(opts.wifiName)}"`,
    `#define WIFI_PASSWORD "${esc(opts.wifiPassword)}"`,
    "#define UDP_PORT 4210",
    "#define LINK_TIMEOUT_MS 500   // motors off when no control packet arrives for this long",
    "#define LOOP_HZ 500",
    `#define MOTOR_ESC ${drone.motorType === "esc" ? 1 : 0}   // 1: brushless ESCs (1000-2000 us pulses), 0: brushed motors on MOSFETs`,
    drone.motorType === "esc" ? "#define PWM_FREQ 400" : "#define PWM_FREQ 20000",
    drone.motorType === "esc" ? "#define PWM_BITS 14" : "#define PWM_BITS 10",
    "",
  ].join("\n");
}

const MAIN_CPP = String.raw`// MakerStudio drone code: MPU-6050 + brushed motors on MOSFETs + Wi-Fi control (UDP).
// The flight controller is flight_core.h, the same maths as the Drone Studio simulator.
// NOT TESTED ON A REAL DRONE YET: read README.md and do the checks with the propellers OFF.
#include <Arduino.h>
#include <Wire.h>
#include <WiFi.h>
#include <WiFiUdp.h>
#include "flight_config.h"
#include "drone_config.h"

static FcController fc;
static FcEstimator est;
static WiFiUDP udp;
static double gyroBias[3] = {0, 0, 0};
static bool armed = false, calibrated = false;
static uint32_t lastPacket = 0, lastTelemetry = 0, tiltSince = 0;
static double sThrottle = 0, sRoll = 0, sPitch = 0, sYaw = 0;
static bool wantArm = false;
static IPAddress pilotIp; static uint16_t pilotPort = 0;
static double batteryVolts = 0;
static uint32_t loops = 0, loopsAt = 0; static double loopHz = 0;
static double sClimb = 0; static bool wantHold = false, holding = false;
#if HEIGHT_SENSOR
#include <VL53L1X.h>
static VL53L1X tof;
static bool tofOk = false;
static double hEst = 0, vzEst = 0;   // height above the floor (m) and climb speed (m/s)
static uint32_t lastTof = 0;
static FcHeightHold hh;
#endif

// --- motors (LEDC PWM; thrust grows about with the square of the throttle: estimate) ---
static void motorWrite(int i, double share) {
  share = fcClamp(share, 0, 1);
#if MOTOR_ESC
  // ESC throttle pulse: 1000 us = stop, 2000 us = full, in a 2500 us (400 Hz) period.
  double us = 1000.0 + sqrt(share) * 1000.0;
  uint32_t duty = (uint32_t)(us / (1000000.0 / PWM_FREQ) * ((1 << PWM_BITS) - 1));
#else
  uint32_t duty = (uint32_t)(sqrt(share) * ((1 << PWM_BITS) - 1));
#endif
#if ESP_ARDUINO_VERSION_MAJOR >= 3
  ledcWrite(MOTOR_PINS[i], duty);
#else
  ledcWrite(i, duty);
#endif
}
static void motorsOff() { for (int i = 0; i < MOTOR_COUNT; i++) motorWrite(i, 0); }
static void motorsBegin() {
  for (int i = 0; i < MOTOR_COUNT; i++) {
    pinMode(MOTOR_PINS[i], OUTPUT); digitalWrite(MOTOR_PINS[i], LOW);
#if ESP_ARDUINO_VERSION_MAJOR >= 3
    ledcAttach(MOTOR_PINS[i], PWM_FREQ, PWM_BITS);
#else
    ledcSetup(i, PWM_FREQ, PWM_BITS); ledcAttachPin(MOTOR_PINS[i], i);
#endif
  }
  motorsOff();
}

// --- MPU-6050 (registers from the MPU-6000/6050 Register Map) ---
static const uint8_t MPU = 0x68;
static void mpuWrite(uint8_t reg, uint8_t v) { Wire.beginTransmission(MPU); Wire.write(reg); Wire.write(v); Wire.endTransmission(); }
static bool mpuBegin() {
  Wire.beginTransmission(MPU); Wire.write(0x75); Wire.endTransmission(false);
  if (Wire.requestFrom(MPU, (uint8_t)1) != 1) return false;
  uint8_t who = Wire.read();
  if (who != 0x68 && who != 0x70 && who != 0x72) { Serial.printf("IMU answered WHO_AM_I 0x%02X (expected 0x68)\n", who); return false; }
  mpuWrite(0x6B, 0x01);  // wake up, gyro clock
  mpuWrite(0x1A, 0x03);  // digital low-pass filter ~44 Hz
  mpuWrite(0x1B, 0x18);  // gyro +-2000 deg/s (16.4 LSB per deg/s)
  mpuWrite(0x1C, 0x10);  // accel +-8 g (4096 LSB per g)
  return true;
}
static bool mpuRead(double gyro[3], double accel[3]) {
  Wire.beginTransmission(MPU); Wire.write(0x3B); if (Wire.endTransmission(false) != 0) return false;
  if (Wire.requestFrom(MPU, (uint8_t)14) != 14) return false;
  int16_t r[7];
  for (int i = 0; i < 7; i++) { int hi = Wire.read(); int lo = Wire.read(); r[i] = (int16_t)((hi << 8) | lo); }
  double a[3] = {r[0] / 4096.0 * 9.80665, r[1] / 4096.0 * 9.80665, r[2] / 4096.0 * 9.80665};
  double g[3] = {r[4] / 16.4 * DEG_TO_RAD, r[5] / 16.4 * DEG_TO_RAD, r[6] / 16.4 * DEG_TO_RAD};
  for (int k = 0; k < 3; k++) {
    accel[k] = IMU_TO_BODY[k * 3] * a[0] + IMU_TO_BODY[k * 3 + 1] * a[1] + IMU_TO_BODY[k * 3 + 2] * a[2];
    gyro[k] = IMU_TO_BODY[k * 3] * g[0] + IMU_TO_BODY[k * 3 + 1] * g[1] + IMU_TO_BODY[k * 3 + 2] * g[2] - gyroBias[k];
  }
  return true;
}
static bool calibrate() {
  // Keep the drone still and level: average the gyro (its zero) and start the attitude from gravity.
  double sum[3] = {0, 0, 0}, sq[3] = {0, 0, 0}, g[3], a[3];
  const int N = 800;
  for (int k = 0; k < 3; k++) gyroBias[k] = 0;
  for (int i = 0; i < N; i++) { if (!mpuRead(g, a)) return false; for (int k = 0; k < 3; k++) { sum[k] += g[k]; sq[k] += g[k] * g[k]; } delay(2); }
  for (int k = 0; k < 3; k++) { double m = sum[k] / N; if (sq[k] / N - m * m > 0.0004) { Serial.println("Moved during calibration: keep it still."); return false; } gyroBias[k] = m; }
  for (int i = 0; i < 400; i++) { mpuRead(g, a); est.gain = 10; est.update(g, a, 0.002); delay(1); }
  est.gain = 2;
  return true;
}

static double tiltOf(const double q[4]) { const double z[3] = {0, 0, 1}; double up[3]; fcRotate(q, z, up); return acos(fcClamp(up[2], -1, 1)); }

static void disarm(const char* why) {
  if (armed) Serial.printf("DISARMED: %s\n", why);
  armed = false; wantArm = false; motorsOff(); fc.reset();
}

static void dropPacket() {
#if ESP_ARDUINO_VERSION_MAJOR >= 3
  udp.clear();
#else
  udp.flush();
#endif
}

// --- control link: 16-byte packets "MSD1", seq, throttle 0..1000, roll/pitch/yaw -1000..1000, flags (bit 0 arm, bit 1 hold), climb -100..100 ---
static void readLink() {
  int size;
  while ((size = udp.parsePacket()) > 0) {
    uint8_t b[16];
    if (size != 16 || udp.read(b, 16) != 16 || memcmp(b, "MSD1", 4) != 0) { dropPacket(); continue; }
    auto i16 = [&](int o) { return (int16_t)(b[o] | (b[o + 1] << 8)); };
    sThrottle = fcClamp(i16(6) / 1000.0, 0, 1);
    sRoll = fcClamp(i16(8) / 1000.0, -1, 1); sPitch = fcClamp(i16(10) / 1000.0, -1, 1); sYaw = fcClamp(i16(12) / 1000.0, -1, 1);
    wantArm = b[14] & 1;
    wantHold = b[14] & 2;
    sClimb = fcClamp((int8_t)b[15] / 100.0, -1, 1);
    pilotIp = udp.remoteIP(); pilotPort = udp.remotePort();
    lastPacket = millis();
  }
}

static void sendTelemetry() {
  if (!pilotPort) return;
  const double* q = est.q;
  // "Up" as the drone sees it: pitch forward (about +X) and roll right (about +Y) are positive.
  double qc[4], up[3]; const double z[3] = {0, 0, 1};
  fcConj(q, qc); fcRotate(qc, z, up);
  double pitch = atan2(up[1], up[2]) * RAD_TO_DEG;
  double roll = atan2(-up[0], up[2]) * RAD_TO_DEG;
  char line[160];
  double height = -1;
#if HEIGHT_SENSOR
  if (tofOk && millis() - lastTof < 300) height = hEst;
#endif
  int n = snprintf(line, sizeof line, "{\"armed\":%d,\"roll\":%.1f,\"pitch\":%.1f,\"yaw\":%.1f,\"volts\":%.2f,\"loopHz\":%.0f,\"calibrated\":%d,\"height\":%.2f,\"hold\":%d}",
                   armed ? 1 : 0, roll, pitch, fcYaw(q) * RAD_TO_DEG, batteryVolts, loopHz, calibrated ? 1 : 0, height, holding ? 1 : 0);
  udp.beginPacket(pilotIp, pilotPort); udp.write((const uint8_t*)line, n); udp.endPacket();
}

static void motorTest() {
  // Bench check with the PROPELLERS OFF: each motor in turn, slowly. Check order and direction.
  if (armed) return;
  Serial.println("Motor test: PROPELLERS OFF. Each motor runs for 1 s at 15 %.");
#if MOTOR_ESC
  Serial.println("ESCs: make sure they are armed (they beep when they see the 1000 us stop pulse at power-on).");
#endif
  for (int i = 0; i < MOTOR_COUNT; i++) { Serial.printf("Motor %d (pin %d)\n", i + 1, MOTOR_PINS[i]); motorWrite(i, 0.15); delay(1000); motorWrite(i, 0); delay(400); }
}

void setup() {
  motorsBegin();  // motors off before anything else
  Serial.begin(115200);
  delay(300);
  Serial.printf("MakerStudio drone code, %s, %d motors\n", BOARD_NAME, MOTOR_COUNT);
  Wire.begin(I2C_SDA, I2C_SCL, 400000);
  if (!mpuBegin()) { Serial.println("No MPU-6050 found: check SDA/SCL/power. Not flying."); while (true) { motorsOff(); delay(1000); } }
  fc.c = &FC_CONFIG;
  for (int tries = 0; tries < 5 && !(calibrated = calibrate()); tries++) delay(1000);
  if (!calibrated) Serial.println("Calibration failed: keep the drone still and restart.");
#if HEIGHT_SENSOR
  tof.setBus(&Wire);
  tof.setTimeout(50);
  if (tof.init()) {
    tof.setDistanceMode(VL53L1X::Long);
    tof.setMeasurementTimingBudget(33000);
    tof.startContinuous(33);
    tofOk = true;
  } else Serial.println("No VL53L1X found: height hold is off (stabilize only).");
  hh.mass = DRONE_MASS_KG; hh.maxThrust = FC_CONFIG.maxThrust; hh.motors = MOTOR_COUNT;
#endif
  WiFi.softAP(WIFI_NAME, WIFI_PASSWORD);
  udp.begin(UDP_PORT);
  Serial.printf("Wi-Fi \"%s\" ready at %s, UDP port %d. Send t for the motor test (propellers off).\n", WIFI_NAME, WiFi.softAPIP().toString().c_str(), UDP_PORT);
}

void loop() {
  static uint32_t last = micros();
  uint32_t now = micros();
  if (now - last < 1000000UL / LOOP_HZ) return;
  double dt = (now - last) / 1e6; last = now;
  if (dt > 0.02) dt = 0.02;
  if (++loops, millis() - loopsAt >= 1000) { loopHz = loops * 1000.0 / (millis() - loopsAt); loops = 0; loopsAt = millis(); }

  if (Serial.available() && Serial.read() == 't') motorTest();
  readLink();
  double gyro[3], accel[3];
  if (!mpuRead(gyro, accel)) { disarm("IMU read failed"); return; }
  est.update(gyro, accel, dt);
  double tilt = tiltOf(est.q);

#if BATTERY_PIN >= 0
  batteryVolts = analogReadMilliVolts(BATTERY_PIN) / 1000.0 * BATTERY_DIVIDER;
  if (armed && batteryVolts > 1 && batteryVolts < 3.0 * BATTERY_CELLS) disarm("battery empty");
#endif

  bool linkOk = lastPacket && millis() - lastPacket < LINK_TIMEOUT_MS;
  if (armed && !linkOk) disarm("no control signal");
  if (!armed && wantArm && linkOk && calibrated && sThrottle < 0.05 && tilt < 15 * DEG_TO_RAD) { armed = true; fc.reset(); Serial.println("ARMED"); }
  if (armed && !wantArm) disarm("pilot");
  if (armed && tilt > 70 * DEG_TO_RAD) { if (!tiltSince) tiltSince = millis(); if (millis() - tiltSince > 200) disarm("tipped over"); } else tiltSince = 0;

  double collective = sThrottle * MOTOR_COUNT;
  holding = false;
#if HEIGHT_SENSOR
  {
    // Height and climb speed: the accelerometer (world up) between distance readings, corrected
    // by each reading (alpha-beta filter). The reading is tilt corrected (sensor looks down).
    const double z[3] = {0, 0, 1}; double upv[3], aw[3];
    fcRotate(est.q, z, upv);
    fcRotate(est.q, accel, aw);
    vzEst += (aw[2] - 9.80665) * dt;
    hEst += vzEst * dt;
    if (tofOk && tof.dataReady()) {
      uint16_t mm = tof.read(false);
      if (tof.ranging_data.range_status == VL53L1X::RangeValid && mm > 0 && mm < 3500 && upv[2] > 0.7) {
        double h = mm / 1000.0 * upv[2];
        double e = h - hEst;
        hEst += 0.3 * e;
        vzEst += (0.05 / 0.033) * e;
        lastTof = millis();
      }
    }
    bool fresh = tofOk && millis() - lastTof < 300;
    if (armed && wantHold && fresh && sThrottle > 0.1) { collective = hh.update(sClimb, vzEst, hEst, upv[2]); holding = true; }
    else hh.reset();   // no sensor reading: stabilize with the throttle lever
  }
#endif
  if (armed) {
    double out[FC_MAX_MOTORS];
    fc.update(est.q, gyro, sRoll, sPitch, sYaw, collective, dt, sThrottle > 0.1, out);
    for (int i = 0; i < MOTOR_COUNT; i++) motorWrite(i, out[i]);
  } else motorsOff();

  if (millis() - lastTelemetry > 100) { lastTelemetry = millis(); sendTelemetry(); }
}
`;

