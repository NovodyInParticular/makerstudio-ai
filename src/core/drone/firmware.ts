export interface DroneCodeProject { name: string; files: { path: string; text: string }[]; notes: string[] }

export function droneCodeProject(drone: Drone, objects: CadObject[], opts: DroneCodeOptions): DroneCodeProject {
  const board = DRONE_BOARDS.find((b) => b.id === opts.boardId);
  if (!board) throw new Error("Choose a board.");
  if (opts.motorPins.length !== drone.motors.length) throw new Error(`Give a pin for each of the ${drone.motors.length} motors.`);
  if (new Set(opts.motorPins).size !== opts.motorPins.length) throw new Error("Two motors share a pin.");
  if (opts.motorPins.some((p) => p === board.sda || p === board.scl || p === opts.batteryPin)) throw new Error("A motor pin is also used for the IMU or the battery.");
  if (!/^[\x20-\x7e]{1,32}$/.test(opts.wifiName)) throw new Error("The Wi-Fi name must be 1-32 plain characters.");
  if (!/^[\x20-\x7e]{8,63}$/.test(opts.wifiPassword)) throw new Error("The Wi-Fi password must be 8-63 plain characters.");
  const report = analyseDrone(drone, objects);
  const notes: string[] = [];
  if (report.thrustToWeight < 1.5) notes.push(`Thrust-to-weight is only ${report.thrustToWeight.toFixed(2)}: it may not fly well (see Will it fly?).`);
  if (report.findings.some((f) => f.verdict === "danger")) notes.push("Will it fly? still shows a red problem: fix it before flying.");
  const ini = [
    "; Generated by MakerStudio Drone Studio",
    `[env:${board.id}]`,
    "platform = espressif32",
    `board = ${board.pioBoard}`,
    "framework = arduino",
    "monitor_speed = 115200",
    "build_flags = -O2",
    ...(opts.heightSensor ? ["lib_deps = pololu/VL53L1X@^1.3.1   ; BSD-3-Clause (ST API) / Pololu"] : []),
    "",
  ].join("\n");
  return {
    name: `Drone - ${board.name}`.replace(/[<>:"/\\|?*\u0000-\u001f]/g, "_"),
    files: [
      { path: "platformio.ini", text: ini },
      { path: "README.md", text: readme(drone, opts, board, report) },
      { path: "include/flight_core.h", text: flightCore },
      { path: "include/flight_config.h", text: flightConfigHeader(drone, objects, report) },
      { path: "include/drone_config.h", text: droneConfigHeader(drone, opts, board, report) },
      { path: "src/main.cpp", text: MAIN_CPP },
    ],
    notes,
  };
}

/** A Wi-Fi password for a new export (letters and digits). */
export function newWifiPassword(random: () => number = Math.random): string {
  const chars = "abcdefghjkmnpqrstuvwxyz23456789";
  return Array.from({ length: 12 }, () => chars[Math.floor(random() * chars.length)]).join("");
}
